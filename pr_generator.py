# pr_generator.py
import json
from pathlib import Path
from github import Github
from github.GithubException import GithubException
from repair_engine import DocRepairEngine

class AutoRemediationPipeline:
    def __init__(self, github_token: str, repo_name: str, base_branch: str = "main"):
        self.gh = Github(github_token)
        self.repo = self.gh.get_repo(repo_name)
        self.base_branch = base_branch
        self.engine = DocRepairEngine()

    def run(self, stale_report_path: str):
        print("🛠️ Starting Phase 3: Auto-Remediation & PR Generation...")
        
        with open(stale_report_path, 'r') as f:
            stale_reports = json.load(f)

        if not stale_reports:
            print("✅ No stale docs to fix. Exiting.")
            return

        # Group changes by file to minimize PR commits
        changes_by_file = {}
        for report in stale_reports:
            file_path = report["doc_id"].split("::")[1] # Extract file path from doc ID
            if file_path not in changes_by_file:
                changes_by_file[file_path] = []
            changes_by_file[file_path].append(report)

        pr_body = "## 🤖 Auto-Healed Documentation\n\n"
        pr_body += "This PR was automatically generated by the Self-Healing Docs pipeline.\n\n"
        
        # We will collect all file updates
        file_updates = {}

        for file_path, reports in changes_by_file.items():
            print(f"\n📄 Processing {file_path}...")
            
            # Read the FULL current file content (not just the snippet from JSON)
            # In a real CI, you'd read this from the workspace.
            full_doc_content = Path(file_path).read_text(encoding='utf-8')
            
            for report in reports:
                doc_id = report["doc_id"]
                chunk_id = report["chunk_id"]
                diagnosis = report["report"]["reason"]
                
                # Fetch the actual new code from the workspace
                code_file = chunk_id.split("::")[1]
                new_code = Path(code_file).read_text(encoding='utf-8')
                
                # 1. Generate Correction
                print(f"   ✍️ Rewriting section: {report['doc_heading']}")
                rewrite = self.engine.generate_correction(
                    original_doc=full_doc_content, # In production, extract just the section
                    new_code=new_code,
                    staleness_diagnosis=diagnosis,
                    doc_heading=report["doc_heading"]
                )

                # 2. Validate Correction
                print(f"   🔍 Validating rewrite (Confidence: {rewrite.confidence:.2f})...")
                validation = self.engine.validate_correction(
                    original_doc=full_doc_content,
                    rewritten_doc=rewrite.rewritten_markdown,
                    new_code=new_code
                )

                if not validation.is_valid:
                    print(f"   ❌ QA Failed: {validation.feedback}. Skipping this section.")
                    pr_body += f"- ❌ **Skipped** `{report['doc_heading']}`: QA failed ({validation.feedback})\n"
                    continue

                # 3. Apply Correction (Simulated replacement for MVP)
                # Note: A production system would use a markdown AST parser to replace 
                # the specific section. For this MVP, we'll just append or do a simple string replace.
                # Here we assume the LLM returned the *entire* file content in `rewritten_markdown`.
                updated_content = rewrite.rewritten_markdown 
                
                file_updates[file_path] = updated_content
                
                # 4. Format PR Body based on Mode
                if rewrite.correction_mode == "auto_fix":
                    pr_body += f"- ✅ **Auto-fixed** `{report['doc_heading']}`: {rewrite.explanation}\n"
                else:
                    pr_body += f"- ⚠️ **Drafted (Needs Review)** `{report['doc_heading']}`: {rewrite.explanation}\n"
                    for todo in rewrite.todos:
                        pr_body += f"  - *TODO: {todo}*\n"

        # 5. Create GitHub PR
        if file_updates:
            self._create_pr(file_updates, pr_body)
        else:
            print("✅ All QA checks failed. No PR created.")

    def _create_pr(self, file_updates: dict, pr_body: str):
        branch_name = "auto-heal/docs-update"
        
        try:
            # Create branch
            sb = self.repo.get_branch(self.base_branch)
            self.repo.create_git_ref(ref=f"refs/heads/{branch_name}", sha=sb.commit.sha)
            print(f"🌿 Created branch {branch_name}")

            # Commit files
            for file_path, content in file_updates.items():
                # Get current file to get its SHA
                contents = self.repo.get_contents(file_path, ref=self.base_branch)
                self.repo.update_file(
                    path=file_path,
                    message=f"docs: auto-heal {file_path}",
                    content=content,
                    sha=contents.sha,
                    branch=branch_name
                )
                print(f"   💾 Committed {file_path}")

            # Open PR
            pr = self.repo.create_pull(
                title="🤖 [Auto-Heal] Documentation Updates",
                body=pr_body,
                head=branch_name,
                base=self.base_branch
            )
            print(f"\n🎉 SUCCESS! PR created: {pr.html_url}")

        except GithubException as e:
            print(f"❌ GitHub API Error: {e}")

